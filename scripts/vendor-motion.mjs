import './style-bundle.mjs';
import {readFileSync,writeFileSync,mkdirSync} from 'node:fs';
import path from 'node:path';
import {root} from './project.mjs';
import {build} from 'esbuild';
mkdirSync(path.join(root,'assets/vendor'),{recursive:true});
const source=readFileSync(path.join(root,'node_modules/gsap/dist/gsap.min.js'),'utf8');
writeFileSync(path.join(root,'assets/vendor/gsap.min.js'),source.replace(/[ \t]+$/gm,'').trimEnd()+'\n');
console.log('Copied pinned GSAP runtime with its license header.');
const scrollTrigger=readFileSync(path.join(root,'node_modules/gsap/dist/ScrollTrigger.min.js'),'utf8');
writeFileSync(path.join(root,'assets/vendor/ScrollTrigger.min.js'),scrollTrigger.trimEnd()+'\n');
await build({entryPoints:[path.join(root,'assets/js/obsidian-scene.js')],outfile:path.join(root,'assets/vendor/obsidian-scene.min.js'),bundle:true,minify:true,format:'esm',target:'es2022',legalComments:'eof'});
console.log('Bundled the lazy-loaded Three.js scene and local ScrollTrigger plugin.');
